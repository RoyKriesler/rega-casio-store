def mov_he(m):
    if not m: return None
    m = m.lower()
    if "spring" in m: return "ספרינג דרייב"
    if "solar" in m or "eco-drive" in m: return "סולארי" + (", עם כיוון רדיו" if "radio" in m else "")
    if "tuning fork" in m: return "קולן"
    if "electric" in m: return "חשמלי"
    if "quartz" in m: return "קוורץ"
    if "manual" in m: return "מכני בכיוון ידני"
    if "10-day" in m: return "מכני, רזרבה של עשרה ימים"
    if "automatic" in m: return "אוטומטי"
    if "mechanical" in m: return "מכני"
    return None

def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

