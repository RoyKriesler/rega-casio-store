seen = set()
for x in data:
    if x["brand"] in DROP_BRANDS: continue
    key = x.get("ref") or x["model"]
    if key not in H:
        raise SystemExit(f"no Hebrew copy for {x['brand']} {key}")
    name, tag, col, cond, price, desc = H[key]
    sl = slug(f"{x['brand']}-{key}")[:60]
    if sl in seen: sl += "-2"
    seen.add(sl)
    specs = [("דגם", x.get("ref") or x["model"])]
    mv = mov_he(x.get("movement"))
    if mv: specs.append(("מנגנון", mv))
    if x.get("diameter_mm"): specs.append(("קוטר", f"{x['diameter_mm']} מ״מ"))
    if x.get("water_resistance_m"): specs.append(("עמידות במים", f"{x['water_resistance_m']} מטר"))
    if cond == "vintage": specs.append(("מצב", "וינטג׳, יד שנייה"))
    photos = []
    for ph in x["photos"][:2]:
        credit = f"{ph['author']} · {ph['license']}"
        photos.append({"id": ph["url"] + (f"#w={WIDTHS[ph['url']][0]}" if ph["url"] in WIDTHS else ""), "alt": f"שעון {HE_BRAND[x['brand']]} {name}", "credit": credit[:120]})
    model_label = (x.get("ref") or x["model"]).upper()
    if len(model_label) > 26: model_label = x["model"].replace(x["brand"], "").strip().upper()[:26]
    out.append({"slug": sl, "brand": x["brand"], "name": name, "model": model_label, "tagline": tag, "collection": col,
                "condition": cond, "price": price, "photos": photos, "description": desc,
                "specs": [{"label": a, "value": b} for a, b in specs]})

